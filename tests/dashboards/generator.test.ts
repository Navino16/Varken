import { describe, it, expect } from 'vitest';
import { GlobalConfigSchema, InputsConfigSchema } from '../../src/config/schemas/config.schema';
import { generateDashboard, MIN_GRAFANA_VERSION, type GrafanaPanel } from '../../src/dashboards/generator';
import type { DashboardSpec, PanelSpec, SourceSpec } from '../../src/dashboards/model';

const queue: SourceSpec = { plugin: 'sonarr', collector: 'queue', type: 'Queue', fields: [{ name: 'size', kind: 'number' }] };
const requests: SourceSpec = { plugin: 'ombi', collector: 'requestCounts', type: 'Request_Counts', fields: [{ name: 'pending', kind: 'number' }] };

function panel(key: string, width: number, sources: SourceSpec[], extra: Partial<PanelSpec> = {}): PanelSpec {
  return { key, title: key, width, height: 4, variants: [{ query: { shape: 'latest', agg: 'last' }, sources }], grafana: { type: 'stat' }, ...extra };
}

const SPEC: DashboardSpec = {
  kind: 'overview',
  title: 'Test',
  bands: [
    {
      key: 'now',
      title: 'Now',
      fixedWindow: '24h',
      panels: [
        panel('a', 12, [queue]),
        panel('missing', 12, [requests]),
        panel('b', 12, [queue]),
        panel('c', 16, [queue], {
          variants: [
            { query: { shape: 'timeBuckets' }, sources: [queue] },
            { query: { shape: 'timeSeries', agg: 'mean', bucket: 'auto' }, sources: [queue], grafana: { type: 'timeseries', title: 'Fallback' } },
          ],
        }),
      ],
    },
    { key: 'empty', title: 'Empty', panels: [panel('d', 8, [requests])] },
    { key: 'period', title: 'Period', panels: [panel('e', 8, [queue, queue])] },
  ],
};

const config = {
  inputs: InputsConfigSchema.parse({
    sonarr: [
      { id: 1, url: 'http://sonarr-secret.test', apiKey: 'sonarr-api-key-1', queue: { enabled: true, intervalSeconds: 30 } },
      { id: 2, url: 'http://sonarr-two.test', apiKey: 'sonarr-api-key-2', queue: { enabled: true, intervalSeconds: 120 } },
    ],
  }),
  global: GlobalConfigSchema.parse({}),
};

const generate = (): ReturnType<typeof generateDashboard> =>
  generateDashboard({ kind: 'overview', output: 'influxdb1', config, pairedPlex: new Set(), version: '9.9.9', spec: SPEC });

const byTitle = (title: string): GrafanaPanel => {
  const found = generate().panels.find((p) => p.title === title);
  if (!found) throw new Error(`no panel ${title}`);
  return found;
};

describe('generateDashboard', () => {
  it('flows panels left to right and leaves out panels without source', () => {
    const panels = generate().panels.map((p) => [p.type, p.title, p.gridPos]);

    expect(panels).toEqual([
      ['row', 'Now', { x: 0, y: 0, w: 24, h: 1 }],
      ['stat', 'a', { x: 0, y: 1, w: 12, h: 4 }],
      ['stat', 'b', { x: 12, y: 1, w: 12, h: 4 }],
      ['timeseries', 'Fallback', { x: 0, y: 5, w: 16, h: 4 }],
      ['row', 'Period', { x: 0, y: 9, w: 24, h: 1 }],
      ['stat', 'e', { x: 0, y: 10, w: 8, h: 4 }],
    ]);
    expect(generate().panels.map((p) => p.id)).toEqual([1, 2, 3, 4, 5, 6]);
  });

  it('renders one target per instance with the datasource placeholder', () => {
    const e = byTitle('e');

    expect(e.targets?.map((t) => t.refId)).toEqual(['A', 'B', 'C', 'D']);
    expect(e.datasource).toEqual({ type: 'influxdb', uid: '${DS_VARKEN}' });
    expect(e.targets?.every((t) => t.datasource.uid === '${DS_VARKEN}')).toBe(true);
  });

  it('pins fixed-window panels to the last 24 hours', () => {
    expect(byTitle('a')).toMatchObject({ timeFrom: '24h', hideTimeOverride: true });
    expect(byTitle('e').timeFrom).toBeUndefined();
  });

  it('sets the minimum interval of auto buckets to the slowest collector', () => {
    expect(byTitle('Fallback').interval).toBe('120s');
    expect(byTitle('a').interval).toBeUndefined();
  });

  it('describes the dashboard for import', () => {
    const dashboard = generate();

    expect(dashboard).toMatchObject({
      uid: 'varken-overview-influxdb1',
      title: 'Test',
      tags: ['varken'],
      description: 'Generated by Varken 9.9.9',
      time: { from: 'now-7d', to: 'now' },
      refresh: '1m',
      schemaVersion: 41,
      graphTooltip: 1,
    });
    expect(dashboard.__inputs).toEqual([{ name: 'DS_VARKEN', label: 'Varken (InfluxDB 1)', description: '', type: 'datasource', pluginId: 'influxdb', pluginName: 'InfluxDB' }]);
    expect(dashboard.__requires).toEqual([
      { type: 'grafana', id: 'grafana', name: 'Grafana', version: MIN_GRAFANA_VERSION },
      { type: 'datasource', id: 'influxdb', name: 'InfluxDB', version: '1.0.0' },
      { type: 'panel', id: 'stat', name: 'stat', version: '' },
      { type: 'panel', id: 'timeseries', name: 'timeseries', version: '' },
    ]);
    expect(MIN_GRAFANA_VERSION).toBe('11.0.0');
  });

  it('copies no URL or API key from the config', () => {
    const json = JSON.stringify(generate());

    expect(json).not.toContain('sonarr-secret.test');
    expect(json).not.toContain('sonarr-api-key');
  });
});

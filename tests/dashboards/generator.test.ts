import { describe, it, expect, afterEach } from 'vitest';
import { GlobalConfigSchema, InputsConfigSchema } from '../../src/config/schemas/config.schema';
import { generateDashboard, MIN_GRAFANA_VERSION, type GrafanaPanel } from '../../src/dashboards/generator';
import type { DashboardSpec, PanelSpec, SourceSpec } from '../../src/dashboards/model';
import { influxql } from '../../src/dashboards/translators/influxql';

const queue: SourceSpec = { plugin: 'sonarr', collector: 'queue', type: 'Queue', fields: [{ name: 'size', kind: 'number' }] };
const requests: SourceSpec = { plugin: 'ombi', collector: 'requestCounts', type: 'Request_Counts', fields: [{ name: 'pending', kind: 'number' }] };

function panel(key: string, width: number, sources: SourceSpec[], extra: Partial<PanelSpec> = {}): PanelSpec {
  return { key, title: key, width, height: 4, variants: [{ query: { shape: 'latest', agg: 'last' }, sources }], grafana: { type: 'stat' }, ...extra };
}

const SPEC: DashboardSpec = {
  kind: 'overview',
  title: 'Test',
  bands: [
    {
      key: 'now',
      title: 'Now',
      fixedWindow: '24h',
      panels: [
        panel('a', 12, [queue]),
        panel('missing', 12, [requests]),
        panel('b', 12, [queue]),
        panel('c', 16, [queue], {
          variants: [
            { query: { shape: 'timeBuckets' }, sources: [queue] },
            { query: { shape: 'timeSeries', agg: 'mean', bucket: 'auto' }, sources: [queue], grafana: { type: 'timeseries', title: 'Fallback' } },
          ],
        }),
      ],
    },
    { key: 'empty', title: 'Empty', panels: [panel('d', 8, [requests])] },
    { key: 'period', title: 'Period', panels: [panel('e', 8, [queue, queue], { grafana: { type: 'timeseries' } })] },
  ],
};

const config = {
  inputs: InputsConfigSchema.parse({
    sonarr: [
      { id: 1, url: 'http://sonarr-secret.test', apiKey: 'sonarr-api-key-1', queue: { enabled: true, intervalSeconds: 30 } },
      { id: 2, url: 'http://sonarr-two.test', apiKey: 'sonarr-api-key-2', queue: { enabled: true, intervalSeconds: 120 } },
    ],
  }),
  global: GlobalConfigSchema.parse({}),
};

const generate = (): ReturnType<typeof generateDashboard> =>
  generateDashboard({ kind: 'overview', output: 'influxdb1', config, pairedPlex: new Map(), version: '9.9.9', spec: SPEC });

const byTitle = (title: string): GrafanaPanel => {
  const found = generate().panels.find((p) => p.title === title);
  if (!found) throw new Error(`no panel ${title}`);
  return found;
};

describe('generateDashboard', () => {
  it('flows panels left to right and leaves out panels without source', () => {
    const panels = generate().panels.map((p) => [p.type, p.title, p.gridPos]);

    expect(panels).toEqual([
      ['row', 'Now', { x: 0, y: 0, w: 24, h: 1 }],
      ['stat', 'a', { x: 0, y: 1, w: 12, h: 4 }],
      ['stat', 'b', { x: 12, y: 1, w: 12, h: 4 }],
      ['timeseries', 'Fallback', { x: 0, y: 5, w: 24, h: 4 }],
      ['row', 'Period', { x: 0, y: 9, w: 24, h: 1 }],
      ['timeseries', 'e', { x: 0, y: 10, w: 24, h: 4 }],
    ]);
    expect(generate().panels.map((p) => p.id)).toEqual([1, 2, 3, 4, 5, 6]);
  });

  it('renders one target per instance with the datasource placeholder', () => {
    const e = byTitle('e');

    expect(e.targets?.map((t) => t.refId)).toEqual(['A', 'B', 'C', 'D']);
    expect(e.datasource).toEqual({ type: 'influxdb', uid: '${DS_VARKEN}' });
    expect(e.targets?.every((t) => t.datasource.uid === '${DS_VARKEN}')).toBe(true);
  });

  it('pins fixed-window panels to the last 24 hours', () => {
    expect(byTitle('a')).toMatchObject({ timeFrom: '24h', hideTimeOverride: true });
    expect(byTitle('e').timeFrom).toBeUndefined();
  });

  it('sets the minimum interval of auto buckets to the slowest collector', () => {
    expect(byTitle('Fallback').interval).toBe('120s');
    expect(byTitle('a').interval).toBeUndefined();
  });

  it('describes the dashboard for import', () => {
    const dashboard = generate();

    expect(dashboard).toMatchObject({
      uid: 'varken-overview-influxdb1',
      title: 'Test',
      tags: ['varken'],
      description: 'Generated by Varken 9.9.9',
      time: { from: 'now-7d', to: 'now' },
      refresh: '1m',
      schemaVersion: 41,
      graphTooltip: 1,
    });
    expect(dashboard.__inputs).toEqual([{ name: 'DS_VARKEN', label: 'Varken (InfluxDB 1)', description: '', type: 'datasource', pluginId: 'influxdb', pluginName: 'InfluxDB' }]);
    expect(dashboard.__requires).toEqual([
      { type: 'grafana', id: 'grafana', name: 'Grafana', version: MIN_GRAFANA_VERSION },
      { type: 'datasource', id: 'influxdb', name: 'InfluxDB', version: '1.0.0' },
      { type: 'panel', id: 'stat', name: 'stat', version: '' },
      { type: 'panel', id: 'timeseries', name: 'timeseries', version: '' },
    ]);
    expect(MIN_GRAFANA_VERSION).toBe('11.0.0');
  });

  it('copies no URL or API key from the config', () => {
    const json = JSON.stringify(generate());

    expect(json).not.toContain('sonarr-secret.test');
    expect(json).not.toContain('sonarr-api-key');
  });
});

describe('short lines', () => {
  it('widen their panels in proportion', () => {
    const spec: DashboardSpec = { kind: 'overview', title: 'L', bands: [{ key: 'b', title: 'B', panels: [panel('x', 8, [queue], { grafana: { type: 'table' } }), panel('y', 4, [queue], { grafana: { type: 'table' } })] }] };
    const panels = generateDashboard({ kind: 'overview', output: 'influxdb1', config, pairedPlex: new Map(), version: '9.9.9', spec }).panels.slice(1);

    expect(panels.map((p) => [p.gridPos.x, p.gridPos.w])).toEqual([
      [0, 16],
      [16, 8],
    ]);
  });
});

describe('stat lines', () => {
  it('stretch to the full width when stats are left out', () => {
    const stats = (n: number): PanelSpec[] => Array.from({ length: n }, (_, i) => ({ ...panel(`s${i}`, 3, i < 5 ? [queue] : [requests]), grafana: { type: 'stat' } }));
    const spec: DashboardSpec = { kind: 'overview', title: 'Stats', bands: [{ key: 'now', title: 'Now', panels: [...stats(8), panel('table', 16, [queue], { grafana: { type: 'table' } })] }] };
    const panels = generateDashboard({ kind: 'overview', output: 'influxdb1', config, pairedPlex: new Map(), version: '9.9.9', spec }).panels;

    expect(panels.filter((p) => p.type === 'stat').map((p) => [p.gridPos.x, p.gridPos.w])).toEqual([
      [0, 5],
      [5, 5],
      [10, 5],
      [15, 5],
      [20, 4],
    ]);
    expect(panels.find((p) => p.type === 'table')?.gridPos).toEqual({ x: 0, y: 5, w: 24, h: 4 });
  });
});

describe('variants', () => {
  const hashes: SourceSpec = { ...queue, fields: [{ name: 'hash', kind: 'string' }] };
  const render = (variants: PanelSpec['variants']): GrafanaPanel[] => {
    const spec: DashboardSpec = { kind: 'overview', title: 'V', bands: [{ key: 'b', title: 'B', panels: [panel('p', 8, [], { variants })] }] };
    return generateDashboard({ kind: 'overview', output: 'influxdb1', config, pairedPlex: new Map(), version: '9.9.9', spec }).panels.slice(1);
  };
  const original = { strings: influxql.strings, tableTransformations: influxql.tableTransformations };

  afterEach(() => {
    Object.assign(influxql, original);
  });

  it('skips a complete variant when the output cannot read one of its sources', () => {
    influxql.strings = 'none';
    const variants = (complete: boolean): PanelSpec['variants'] => [
      { query: { shape: 'latest', agg: 'last' }, sources: [queue, hashes], complete, grafana: { title: 'All' } },
      { query: { shape: 'latest', agg: 'count' }, sources: [queue], grafana: { title: 'Fallback' } },
    ];

    expect(render(variants(true)).map((p) => [p.title, p.targets?.length])).toEqual([['Fallback', 2]]);
    expect(render(variants(false)).map((p) => [p.title, p.targets?.length])).toEqual([['All', 2]]);
  });

  it('sizes the panel from the rendered variant', () => {
    const sized = panel('sized', 8, [], { variants: [{ query: { shape: 'latest', agg: 'last' }, sources: [queue], size: [16, 9] }], grafana: { type: 'timeseries' } });
    const spec: DashboardSpec = { kind: 'overview', title: 'S', bands: [{ key: 'b', title: 'B', panels: [sized, panel('next', 8, [queue], { grafana: { type: 'table' } })] }] };
    const [p] = generateDashboard({ kind: 'overview', output: 'influxdb1', config, pairedPlex: new Map(), version: '9.9.9', spec }).panels.slice(1);

    expect(p.gridPos).toMatchObject({ w: 16, h: 9 });
  });

  it('puts the translator table transformations before the panel ones on table shapes only', () => {
    influxql.tableTransformations = [{ id: 'x' }];
    const own = { type: 'table', transformations: [{ id: 'merge' }] };
    const [table] = render([{ query: { shape: 'latestTable' }, sources: [queue], grafana: own }]);
    const [series] = render([{ query: { shape: 'latest', agg: 'last' }, sources: [queue], grafana: own }]);
    const [bare] = render([{ query: { shape: 'topN', agg: 'count' }, sources: [queue], grafana: { type: 'table' } }]);

    expect(table.transformations).toEqual([{ id: 'x' }, { id: 'merge' }]);
    expect(series.transformations).toEqual([{ id: 'merge' }]);
    expect(bare.transformations).toEqual([{ id: 'x' }]);
  });
});

describe('per-instance bands', () => {
  const ombi: SourceSpec = { ...requests };
  const detailed = (collapsed: boolean): DashboardSpec => ({
    kind: 'detailed',
    title: 'D',
    bands: [
      { key: 'sonarr', title: 'Sonarr', perInstance: 'sonarr', collapsed, panels: [panel('a', 12, [queue]), panel('b', 24, [queue], { grafana: { type: 'table' } })] },
      { key: 'ombi', title: 'Ombi', perInstance: 'ombi', collapsed, panels: [panel('o', 12, [ombi])] },
    ],
  });
  const render = (collapsed = true, inputs = config.inputs): GrafanaPanel[] =>
    generateDashboard({ kind: 'detailed', output: 'influxdb1', config: { ...config, inputs }, pairedPlex: new Map(), version: '9.9.9', spec: detailed(collapsed) }).panels;
  const nested = (row: GrafanaPanel): GrafanaPanel[] => (row.panels as GrafanaPanel[] | undefined) ?? [];

  it('gives each configured instance its own collapsed row', () => {
    const rows = render();

    expect(rows.map((p) => [p.type, p.title, p.collapsed, p.gridPos])).toEqual([
      ['row', 'Sonarr 1', true, { x: 0, y: 0, w: 24, h: 1 }],
      ['row', 'Sonarr 2', true, { x: 0, y: 1, w: 24, h: 1 }],
    ]);
    expect(nested(rows[0]).map((p) => [p.title, p.gridPos])).toEqual([
      ['a', { x: 0, y: 1, w: 24, h: 4 }],
      ['b', { x: 0, y: 5, w: 24, h: 4 }],
    ]);
    expect(nested(rows[1]).every((p) => p.gridPos.y >= 2)).toBe(true);
  });

  it('reads only the row instance', () => {
    const queries = nested(render()[1]).flatMap((p) => (p.targets ?? []).map((t) => String(t.query)));

    expect(queries).toHaveLength(2);
    expect(queries.every((q) => q.includes(`"server" = '2'`) && !q.includes(`"server" = '1'`))).toBe(true);
  });

  it('numbers rows and nested panels once each', () => {
    const rows = render();
    const ids = rows.flatMap((row) => [row.id, ...nested(row).map((p) => p.id)]);

    expect(ids).toEqual([1, 2, 3, 4, 5, 6]);
  });

  it('requires the panel types of collapsed rows', () => {
    const dashboard = generateDashboard({ kind: 'detailed', output: 'influxdb1', config, pairedPlex: new Map(), version: '9.9.9', spec: detailed(true) });

    expect(dashboard.__requires.filter((r) => (r as { type: string }).type === 'panel').map((r) => (r as { id: string }).id)).toEqual(['stat', 'table']);
  });

  it('leaves out an instance without enabled collector', () => {
    const inputs = InputsConfigSchema.parse({ sonarr: [{ id: 1, url: 'http://s.test', apiKey: 'k', queue: { enabled: false } }, { id: 2, url: 'http://t.test', apiKey: 'k', queue: { enabled: true } }] });

    expect(render(true, inputs).map((p) => p.title)).toEqual(['Sonarr 2']);
  });

  it('keeps the panels of an open row at the top level', () => {
    expect(render(false).map((p) => [p.type, p.title, p.gridPos.y])).toEqual([
      ['row', 'Sonarr 1', 0],
      ['stat', 'a', 1],
      ['table', 'b', 5],
      ['row', 'Sonarr 2', 9],
      ['stat', 'a', 10],
      ['table', 'b', 14],
    ]);
  });
});

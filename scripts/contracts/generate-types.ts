import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {
  contractHash,
  loadContract,
  loadManifest,
  OPENAPI_TYPESCRIPT_VERSION,
  type ServiceId,
} from '../../tests/contracts/lib/spec';

const outputDir = path.resolve(__dirname, '../../src/types/generated');

function generate(service: ServiceId): void {
  const { entry, spec } = loadContract(service);
  const workDir = fs.mkdtempSync(path.join(os.tmpdir(), `varken-contract-${service}-`));
  const input = path.join(workDir, 'spec.json');
  const output = path.join(workDir, 'types.ts');

  try {
    fs.writeFileSync(input, JSON.stringify(spec));
    execFileSync('npx', ['-y', `openapi-typescript@${OPENAPI_TYPESCRIPT_VERSION}`, input, '-o', output], {
      stdio: 'inherit',
    });
    const header = [
      `// Generated by \`npm run contracts:types\` from tests/contracts/specs/${entry.file} — do not edit.`,
      `// contract-hash: ${contractHash(service)}`,
    ].join('\n');
    fs.mkdirSync(outputDir, { recursive: true });
    fs.writeFileSync(path.join(outputDir, `${service}.ts`), `${header}\n${fs.readFileSync(output, 'utf8')}`);
    console.warn(`Generated src/types/generated/${service}.ts`);
  } finally {
    fs.rmSync(workDir, { recursive: true, force: true });
  }
}

const requested = process.argv.slice(2) as ServiceId[];
const manifest = loadManifest();
const services = requested.length > 0 ? requested : (Object.keys(manifest) as ServiceId[]);

for (const service of services) {
  if (!manifest[service]) {
    throw new Error(`Unknown contract service: ${service}`);
  }
  generate(service);
}
